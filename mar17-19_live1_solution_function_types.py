""" 
Lesson goals:
    - Understand 2 types of functions:
        1. Perform a task
        2. Return a value
    - Write functions that perform a task
    - Write functions that return a value
"""

""" Study these """
# ---------------------------------------
# Type 1: Built-in function that performs a task.
#   task: prints a greeting

print("Hi there")

print("\n\n")
# ---------------------------------------
# Type 1:  List method that performs a task
#   task: adds an item to the end of the list

students = ["Student A", "Student B", "Student C"]
print(students.append("Student D"))

print("\n\n")
# ---------------------------------------
# Type 2: Built-in function that returns a value
#   value returned - a rounded number
print(round(1.9))

print("\n\n")
# ---------------------------------------
# Type 2: String method that returns a value
#   value returned - a string converted to a title case
name ="Larry"
print(name.title())

print("\n\n")
